    return Geometry(mshr.CSGRotation(geom_object1.pyobject, point, angle))
end
function CSGRotation(geom_object1::Geometry, point_axis, point_center, angle)
    return Geometry(mshr.CSGRotation(geom_object1.pyobject, point_axis, point_center, angle))
end

"""
    CSGTranslation(geom_object1::Geometry, translation_point)

Translate an mshr geometry.

# Arguments

- `geom_object1`: Geometry to translate.
- `translation_point`: Translation vector or point passed to mshr.
"""
