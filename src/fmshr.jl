"""
    CSGRotation(geom_object1::Geometry, angle)
    CSGRotation(geom_object1::Geometry, point, angle)
    CSGRotation(geom_object1::Geometry, point_axis, point_center, angle)

Rotate an mshr geometry using one of the supported rotation signatures.

# Arguments

- `geom_object1`: Geometry to rotate.
- `angle`: Rotation angle.
- `point`: Optional rotation point.
- `point_axis`: Optional rotation axis.
- `point_center`: Optional center of rotation.
"""
function CSGRotation(geom_object1::Geometry, angle)
    return Geometry(mshr.CSGRotation(geom_object1.pyobject, angle))
end
